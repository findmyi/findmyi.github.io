/* ==========================================================================
   处境自测 · 题库与计分
   --------------------------------------------------------------------------
   两条设计原则，都是踩坑换来的：

   ① 让用户感觉「我在看自己」，不是「我在被检查」
      ✗ 题目下面写「英耀：叠叠问此事，定然此事缺」——用户会立刻意识到
        自己被一套方法论在解剖，防御心起来，答案就不真了。
      ✗ 「这题测的是你的位置感」——同理。
      ✓ hint 只用来消除题面歧义（「算直接汇报的，不算协助」），
        其余一概不写。宁可没有提示，也不要暴露诊断意图。

   ② 不同的人卡在不同的事上，不能只问职场
      学生、全职带娃的、退休的、自己做事的 —— 「有几个人向你汇报」
      这道题对他们完全无效。
      所以：一道分流题 → 八道跨领域通用题 → 四道该领域专属题。

   流程：
     分流题（选领域）→ 通用 8 题 + 领域 4 题 = 12 题计分
     → 每题给 1~2 个阶段权重（合计 3）→ 总分最高者为结果

   结果阶段（六爻）：
     P1 还没起来 / P2 刚被看见 / P3 最难的中段
     P4 在关口上 / P5 到顶了   / P6 该收了

   ⚠️ 对外文案统一「处境自测」，不出现「测卦 / 算命 / 预测 / 吉凶」。
   ========================================================================== */

