   设计原则（借《英耀赋》的观察法）：

     「入门先观来意」——先判身份与位置，不先问情绪
     「叠叠问此事，定然此事缺」——反复提到的事，就是他卡住的地方
     「士子问前程，商贾问财帛」——不同位置的人，关心的东西不一样

