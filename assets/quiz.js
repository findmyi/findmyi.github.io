  /* ---------------- 计分 ---------------- */

  /** 某轮要用哪些题（不含分流题） */
  function questionsFor(track) {
    return COMMON.concat(TRACKS[track] || TRACKS.work);
  }

  function score(answers, track) {
    const total = { P1: 0, P2: 0, P3: 0, P4: 0, P5: 0, P6: 0 };
    for (const q of questionsFor(track)) {
      const pick = answers[q.id];
      if (pick == null) continue;
      const opt = q.opts[pick];
      if (!opt || !opt.s) continue;
      for (const [k, v] of Object.entries(opt.s)) total[k] = (total[k] || 0) + v;
    }
    let best = 'P3';
    let bestScore = -1;
    const order = ['P1', 'P2', 'P3', 'P4', 'P5', 'P6'];
    for (const k of order) {
      if (total[k] > bestScore) { bestScore = total[k]; best = k; }
    }
    return { stage: best, scores: total, answered: Object.keys(answers).length };
  }

  /** 从该阶段挑三条最像的处境（不同卦，保证三个角度） */
  function pickSituations(stageCode, situData, n) {
    const items = ((situData && situData.items) || []).filter((x) => x.stage === stageCode);
    if (!items.length) return [];
    const want = n || 3;
    const picked = [];
    const usedGua = new Set();
    for (const it of items) {
      if (picked.length >= want) break;
      if (usedGua.has(it.gua)) continue;
      usedGua.add(it.gua);
      picked.push(it);
    }
    for (const it of items) {
      if (picked.length >= want) break;
      if (!picked.includes(it)) picked.push(it);
    }
    return picked;
  }

