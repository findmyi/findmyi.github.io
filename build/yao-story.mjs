/* ==========================================================================
   卦 · 史事（首页小面板的引流钩子）
   --------------------------------------------------------------------------
   位置：首页方阵右侧小面板的六爻之下。
   写法：两三句话，讲到关键处【故意用省略号断掉】——
        读者的好奇心被吊起来，才会去点「完整阅读」。
        所以这里的 text 一律不满、不完整，这是设计，不是偷懒。

   ⚠️ 诚信底线（与本站其它部分一致）：

     · 只写正史有据的史事（以《史记》《汉书》《资治通鉴》为准）。
     · 故事与本卦的关联若属义理推演（非爻辞原文所指），
       措辞用「正合此卦 / 可以类比」，不用「本卦讲的就是」。
     · 拿不准的宁可留空 —— 前端会自动隐藏整块，不会露馅。

   字段：
     who    人物（2–4 字）
     era    时代（如「西汉」）
     text   两三句，末尾用……断开（40–60 字为宜）
     level  'dian'（爻辞原文即此事）| 'yi'（义理类比）
   ========================================================================== */

